USE YSSYSTEM_SOLUTION
GO

CREATE TABLE TB_EQUIPMENT
(
	EQUIP_ID	NVARCHAR(200)	PRIMARY KEY,
	EQUIP_NAME	NVARCHAR(200)	NOT NULL,
	LINE_NAME	NVARCHAR(200)	NOT NULL,
	STATUS		NVARCHAR(200)	DEFAULT 'IDLE',
	CREATE_DT	DATETIME		NULL			DEFAULT GETDATE()
)

CREATE TABLE TB_EQUIP_LOG
(
	LOG_ID		BIGINT			PRIMARY KEY	IDENTITY(1, 1),
	EQUIP_ID	NVARCHAR(200)	NULL,
	LOG_TYPE	NVARCHAR(200)	NULL,
	LOG_MSG		NVARCHAR(200)	NULL,
	OCCUR_DT	DATETIME		NULL		DEFAULT GETDATE()
)
GO