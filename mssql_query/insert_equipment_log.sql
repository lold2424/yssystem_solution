SELECT
    L.LOG_ID,
    E.EQUIP_ID,
    E.EQUIP_NAME,
    E.LINE_NAME,
    E.STATUS,
    L.LOG_TYPE,
    L.LOG_MSG,
    L.OCCUR_DT
FROM dbo.TB_EQUIPMENT  AS E
INNER JOIN dbo.TB_EQUIP_LOG AS L
    ON E.EQUIP_ID = L.EQUIP_ID
ORDER BY L.LOG_ID;
GO

SELECT L.*
FROM dbo.TB_EQUIP_LOG AS L
LEFT JOIN dbo.TB_EQUIPMENT AS E
    ON L.EQUIP_ID = E.EQUIP_ID
WHERE E.EQUIP_ID IS NULL;
GO

SELECT
    E.EQUIP_ID,
    E.EQUIP_NAME,
    E.STATUS,
    COUNT(L.LOG_ID) AS LOG_CNT
FROM dbo.TB_EQUIPMENT AS E
LEFT JOIN dbo.TB_EQUIP_LOG AS L
    ON E.EQUIP_ID = L.EQUIP_ID
GROUP BY E.EQUIP_ID, E.EQUIP_NAME, E.STATUS
ORDER BY E.EQUIP_ID;
GO